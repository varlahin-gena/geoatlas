package connectorsconf

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"geoatlas/internal/fileatomic"
	"geoatlas/internal/usecase/connectors"
)

// Writer renders syslog-ng conf.d fragment for connectors.
type Writer struct {
	Path string // absolute path of zz_connectors.conf
}

func New(path string) *Writer {
	return &Writer{Path: strings.TrimSpace(path)}
}

const confTemplate = `# GENERATED by geoatlas — do not edit by hand.
# Apply via POST /api/connectors/apply
{{- range .}}
{{- if .Enabled}}
{{- if or (eq .Protocols "udp") (eq .Protocols "both")}}

source s_{{.SafeID}}_udp {
    network(
        transport("udp")
        port({{.Port}})
        so-rcvbuf(` + "`udp_rcvbuf`" + `)
        log-iw-size(` + "`iw_size`" + `)
        flags(store-raw-message)
    );
};

template t_{{.SafeID}}_udp {
    template("@@ga/udp/` + "`ga_ingest_token`" + `/{{.ID}}/@@${RAWMSG}\n");
    template_escape(no);
};

destination d_{{.SafeID}}_udp {
    network(
        "backend"
        port(1514)
        transport("tcp")
        template(t_{{.SafeID}}_udp)
        persist-name("ingest-{{.SafeID}}-udp")
        time-reopen(5)
        so-sndbuf(16777216)
        flush_lines(100)
        disk-buffer(
            reliable(no)
            flow-control-window-size(` + "`fifo_size`" + `)
            capacity-bytes(` + "`disk_buf`" + `)
            dir("/var/lib/syslog-ng-buffer/{{.SafeID}}-udp")
        )
    );
};

log {
    source(s_{{.SafeID}}_udp);
    destination(d_{{.SafeID}}_udp);
    flags(flow-control);
};
{{- end}}
{{- if or (eq .Protocols "tcp") (eq .Protocols "both")}}

source s_{{.SafeID}}_tcp {
    network(
        transport("tcp")
        port({{.Port}})
        so-rcvbuf(` + "`tcp_rcvbuf`" + `)
        max-connections(` + "`tcp_max_conn`" + `)
        log-iw-size(` + "`tcp_iw_size`" + `)
        flags(store-raw-message)
    );
};

template t_{{.SafeID}}_tcp {
    template("@@ga/tcp/` + "`ga_ingest_token`" + `/{{.ID}}/@@${RAWMSG}\n");
    template_escape(no);
};

destination d_{{.SafeID}}_tcp {
    network(
        "backend"
        port(1514)
        transport("tcp")
        template(t_{{.SafeID}}_tcp)
        persist-name("ingest-{{.SafeID}}-tcp")
        time-reopen(5)
        so-sndbuf(16777216)
        flush_lines(100)
        disk-buffer(
            reliable(no)
            flow-control-window-size(` + "`fifo_size`" + `)
            capacity-bytes(` + "`disk_buf`" + `)
            dir("/var/lib/syslog-ng-buffer/{{.SafeID}}-tcp")
        )
    );
};

log {
    source(s_{{.SafeID}}_tcp);
    destination(d_{{.SafeID}}_tcp);
    flags(flow-control);
};
{{- end}}
{{- end}}
{{- end}}
`

type renderRow struct {
	ID        string
	SafeID    string
	Port      int
	Protocols string
	Enabled   bool
}

var tmpl = template.Must(template.New("connectors").Parse(confTemplate))

// Write renders enabled connectors into Path.
func (w *Writer) Write(doc connectors.Document) (string, error) {
	if w == nil || w.Path == "" {
		return "", fmt.Errorf("connectors conf path is empty")
	}
	rows := make([]renderRow, 0, len(doc.Connectors))
	for _, c := range doc.Connectors {
		rows = append(rows, renderRow{
			ID:        c.ID,
			SafeID:    sanitizeID(c.ID),
			Port:      c.Port,
			Protocols: c.Protocols,
			Enabled:   c.Enabled,
		})
	}
	var b strings.Builder
	if err := tmpl.Execute(&b, rows); err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(w.Path), 0o755); err != nil {
		return "", err
	}
	if err := fileatomic.WriteFile(w.Path, []byte(b.String()), 0o644); err != nil {
		return "", err
	}
	return w.Path, nil
}

func sanitizeID(id string) string {
	id = strings.ToLower(strings.TrimSpace(id))
	var b strings.Builder
	for _, r := range id {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
		case r == '-' || r == '_':
			b.WriteByte('_')
		}
	}
	out := b.String()
	if out == "" {
		return "conn"
	}
	return out
}
