#!/usr/bin/env bash
# Full-stack compose smoke for nightly CI (not a PR gate).
# Writes a disposable .env, validates compose config, up --build, probes health, down.
#
#   bash scripts/ci-compose-smoke.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

fail() { echo "ci-compose-smoke FAIL: $*" >&2; exit 1; }
ok() { echo "ok: $*"; }

command -v docker >/dev/null 2>&1 || fail "docker is not installed"
docker info >/dev/null 2>&1 || fail "docker daemon is not running"
docker compose version >/dev/null 2>&1 || fail "docker compose is required"

HTTP_PORT="${HTTP_PORT:-18080}"
COMPOSE_PROJECT_NAME="${COMPOSE_PROJECT_NAME:-geoatlas-ci-smoke}"
export HTTP_PORT COMPOSE_PROJECT_NAME

# Disposable CI secrets (not production). 32+ hex-like tokens satisfy start.sh checks.
CLICKHOUSE_PASSWORD="${CLICKHOUSE_PASSWORD:-ci_smoke_clickhouse_password_32ch}"
INGEST_SHARED_SECRET="${INGEST_SHARED_SECRET:-ci_smoke_ingest_shared_secret_32}"
API_AUTH_TOKEN="${API_AUTH_TOKEN:-ci_smoke_api_auth_token_32charsxx}"
SESSION_SECRET="${SESSION_SECRET:-ci_smoke_session_secret_32charsxxx}"
AUTH_ADMIN_PASSWORD="${AUTH_ADMIN_PASSWORD:-CiSmokeAdminPass1}"

cleanup() {
  echo "::group::compose down"
  docker compose --env-file .env --profile syslog --profile stats down -v --remove-orphans || true
  echo "::endgroup::"
}
trap cleanup EXIT

umask 077
cat >.env <<EOF
# Generated by scripts/ci-compose-smoke.sh — do not use in production.
COMPOSE_PROJECT_NAME=${COMPOSE_PROJECT_NAME}
COMPOSE_PROFILES=syslog,stats
HTTP_PORT=${HTTP_PORT}
HTTPS_ENABLED=0
HTTP_REDIRECT=0
CLICKHOUSE_PASSWORD=${CLICKHOUSE_PASSWORD}
INGEST_SHARED_SECRET=${INGEST_SHARED_SECRET}
INGEST_ALLOW_FROM=syslog-ng
API_AUTH_TOKEN=${API_AUTH_TOKEN}
SESSION_SECRET=${SESSION_SECRET}
AUTH_ADMIN_USER=admin
AUTH_ADMIN_PASSWORD=${AUTH_ADMIN_PASSWORD}
AUTH_ADMIN_MUST_RESET=0
GA_ALLOW_INSECURE=0
REPUTATION_FETCH_ENABLED=false
ANOMALY_ENABLED=false
EOF
ok "wrote .env"

# Bind-mount stubs (gitignored in real installs).
echo '{"profile":"ci-smoke"}' >install-profile.json
echo '{"version":"ci","source":"ci","ref":"ci","commit":"","display":"ci-smoke"}' >install-meta.json

mkdir -p syslog-ng.d certs
esc="${INGEST_SHARED_SECRET//\\/\\\\}"
esc="${esc//\"/\\\"}"
cat >syslog-ng.d/zz_ingest_auth.conf <<EOF
# Generated by ci-compose-smoke.sh
@define ga_ingest_token "${esc}"
EOF
ok "install stubs + ingest auth"

# Explicit profiles: don't rely solely on COMPOSE_PROFILES in .env for `up`.
compose=(docker compose --env-file .env --profile syslog --profile stats)

echo "::group::docker compose config"
"${compose[@]}" config >/dev/null
echo "::endgroup::"
ok "compose config"

echo "::group::docker compose up"
"${compose[@]}" up -d --build --wait --wait-timeout 300
echo "::endgroup::"
ok "compose up --wait"

base="http://127.0.0.1:${HTTP_PORT}"
wait_http() {
  local path="$1" want="${2:-200}" i
  for i in $(seq 1 60); do
    code="$(curl -sS -o /tmp/ga-smoke-body.json -w '%{http_code}' "${base}${path}" || true)"
    if [[ "$code" == "$want" ]]; then
      ok "${path} → ${code}"
      return 0
    fi
    sleep 2
  done
  echo "last body:" >&2
  cat /tmp/ga-smoke-body.json >&2 || true
  fail "${path} did not return ${want} (last=${code:-none})"
}

wait_http /health 200
wait_http /api/live 200
wait_http /api/ready 200

# Edge /health is nginx stub; ready requires ClickHouse + ingest.
grep -q '"ok"' /tmp/ga-smoke-body.json || fail "/api/ready body missing ok"
ok "probes"

echo "ci-compose-smoke: all checks passed"
